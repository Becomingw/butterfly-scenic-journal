'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const yaml=require('js-yaml'),{unescapeHTML}=require('hexo-util');
const {normalize,loadEntries,renderTimeline,musicBlock}=require('./lib/moments');
const options={now:Date.parse('2026-11-01T00:00:00Z'),zone:'Asia/Shanghai'};
const raw={date:'2024-12-31T20:00:00Z',_content:'日常 hello'};
assert.equal(normalize({...raw,published:false},'draft',options),null);
assert.equal(normalize({...raw,date:'2099-01-01T00:00:00Z'},'future',options),null);
assert.equal(normalize(raw,'中文日常',options).year,'2025');
assert.equal(normalize(raw,'midnight',options).displayDate,'2025-01-01 04:00');
for(const date of ['2024-02-30T00:00:00Z','bad','2024-01-01'])assert.throws(()=>normalize({...raw,date},'invalid',options));
assert.throws(()=>normalize({...raw,images:[{url:'javascript:alert(1)'}]},'bad-image',options));
assert.throws(()=>normalize({...raw,_content:''},'empty',options));
const escaped=renderTimeline([normalize({...raw,author:'<script>bad</script>',images:[{url:'/photo.png',alt:'" onerror="bad'}]},'safe',options)],s=>`<p>${s}</p>`);
assert.ok(!escaped.includes('<strong><script>'));assert.ok(!escaped.includes(' onerror="'));
assert.ok(unescapeHTML(musicBlock('https://music.163.com/outchain/player?type=2&id=1&auto=1')).includes('auto=0'));
assert.ok(!musicBlock('https://example.com/').includes('<iframe'));
const config=yaml.load(fs.readFileSync('_config.yml','utf8'));
const entries=loadEntries('content/moments',{zone:config.timezone,author:config.author});
const html=fs.readFileSync('public/moments/index.html','utf8');
assert.equal((html.match(/class="moment-card"/g)||[]).length,entries.length);
assert.equal(new Set(entries.map(e=>e.id)).size,entries.length);
for(let i=1;i<entries.length;i++)assert.ok(entries[i-1].timestamp>=entries[i].timestamp);
for(const e of entries)for(const url of [e.avatar,...e.images.map(i=>i.url)].filter(u=>u.startsWith('/'))){
  assert.ok(fs.statSync(path.join('public',url)).size>0,`Missing asset: ${url}`);
}
for(const file of ['public/css/moments.css','public/js/moments.js'])assert.ok(fs.statSync(file).size>0);
assert.ok(fs.readFileSync('public/sitemap.xml','utf8').includes('/moments/'));
const theme=yaml.load(fs.readFileSync('_config.butterfly.yml','utf8'));
assert.ok(theme.menu['更多||fas fa-ellipsis-h']['碎碎念'].startsWith('/moments/'));
const collections=yaml.load(fs.readFileSync('source/admin/config.yml','utf8')).collections;
const collection=collections.find(c=>c.name==='moments');
assert.equal(collection.folder,'content/moments');assert.equal(collection.create,true);
for(const name of ['title','date','body','images','published'])assert.ok(collection.fields.some(f=>f.name===name));
assert.ok(collections.find(c=>c.name==='posts').fields.some(f=>f.name==='cover'&&f.widget==='image'));
assert.ok(!fs.readFileSync('source/admin/index.html','utf8').includes('admin-shortcuts'));
assert.ok(!fs.existsSync('public/content/moments'));
const journey=JSON.parse(fs.readFileSync('public/journey-data.json','utf8'));
assert.equal(journey.moments.count,entries.length);
assert.deepEqual(journey.moments.entries.map(p=>p.url).sort(),entries.map(e=>'/moments/#'+encodeURIComponent(e.id)).sort());
console.log(`PASS: ${entries.length} moments, images, menu/CMS, drafts/future timestamps, timezone boundaries, escaping and journey links.`);
